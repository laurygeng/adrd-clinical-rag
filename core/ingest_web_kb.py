#!/usr/bin/env python3
"""
Incremental Web KB Ingestion Tool
Used to parse Markdown files with YAML Metadata generated by archive_web_context_to_kb.py, 
and insert them into the underlying ChromaDB.
"""

import os
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

import re
import yaml
import chromadb
from langchain_core.documents import Document
from langchain_text_splitters import RecursiveCharacterTextSplitter
from core.rag_config import config

def parse_markdown_with_frontmatter(file_path: Path) -> Document:
    """Extract YAML Front Matter from Markdown to use as Langchain Vector Store Metadata"""
    with open(file_path, 'r', encoding='utf-8') as f:
        content = f.read()

    metadata = {}
    # Match YAML format
    match = re.match(r'^---\s*\n(.*?)\n---\s*\n(.*)', content, re.DOTALL)
    if match:
        yaml_text = match.group(1)
        body = match.group(2).strip()
        try:
            metadata = yaml.safe_load(yaml_text) or {}
        except Exception as e:
            print(f"⚠️ Failed to parse metadata for {file_path.name}: {e}")
    else:
        body = content.strip()
        
    # Preserve key provenance information
    metadata['source_file'] = file_path.name
    return Document(page_content=body, metadata=metadata)

def ingest_archived_web_docs():
    base_dir = Path(__file__).resolve().parents[1] / "knowledge_base" / "raw_files" / "web_external" / "articles"
    if not base_dir.exists():
        print(f"❌ Directory does not exist: {base_dir}")
        return

    markdown_files = list(base_dir.glob("*.md"))
    if not markdown_files:
        print("ℹ️ No incremental web knowledge files found for ingestion.")
        return

    print(f"📥 Found {len(markdown_files)} web expansion documents, extracting metadata...")
    docs = [parse_markdown_with_frontmatter(f) for f in markdown_files]

    # Split according to rag_config (maintaining compatibility with parent-child chunking strategy)
    print("✂️ Performing text chunking...")
    text_splitter = RecursiveCharacterTextSplitter(
        chunk_size=config.child_chunk_size,
        chunk_overlap=config.child_overlap_size if hasattr(config, 'child_overlap_size') else 40
    )
    split_docs = text_splitter.split_documents(docs)
    
    # Get the same Chroma instance as in advanced_retriever
    chroma_persist_dir = Path(__file__).resolve().parents[1] / "knowledge_base" / "braincheck_vectordb"
    collection_name = "braincheck_advanced"
    
    print(f"🚀 Connecting to underlying vector database (Collection: {collection_name}) ...")
    client = chromadb.PersistentClient(path=str(chroma_persist_dir))
    
    try:
        collection = client.get_collection(collection_name)
    except Exception:
        print("❌ Could not find existing collection. Please ensure ingest_documents.py has been run to initialize the DB.")
        return

    # Using HuggingFaceEmbeddings here, importing the exact same embedding model as AdvancedRetriever
    from langchain_community.embeddings import HuggingFaceBgeEmbeddings
    embeddings = HuggingFaceBgeEmbeddings(
        model_name=config.embed_model_name,
        encode_kwargs={"normalize_embeddings": getattr(config, 'embed_normalize', True)}
    )

    from langchain_community.vectorstores import Chroma
    vector_store = Chroma(
        client=client, 
        collection_name=collection_name, 
        embedding_function=embeddings
    )

    # Deduplication check (based on source filename) to avoid duplicate insertions
    existing_sources = set(metadata.get('source_file') for metadata in collection.get()['metadatas'] if metadata)
    
    new_docs = [d for d in split_docs if d.metadata.get('source_file') not in existing_sources]
    
    if not new_docs:
        print("✅ All incremental files already exist in the database. Skipping ingestion.")
        return

    print(f"💾 Writing {len(new_docs)} new chunks into ChromaDB knowledge base...")
    vector_store.add_documents(new_docs)
    print("🎉 Incremental knowledge update successful!")

if __name__ == "__main__":
    ingest_archived_web_docs()